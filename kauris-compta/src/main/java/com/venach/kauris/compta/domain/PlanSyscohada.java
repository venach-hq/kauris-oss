    /** Le libellé d'un compte du plan, ou celui de son plus proche parent (521100 → 521000), ou vide. */
    public static String libelle(String numero) {
        for (Ligne l : COMPTES) {
            if (l.numero().equals(numero)) {
                return l.libelle();
            }
        }
        for (int n = numero.length() - 1; n >= 2; n--) {
            String prefixe = numero.substring(0, n);
            for (Ligne l : COMPTES) {
                if (l.numero().replaceAll("0+$", "").equals(prefixe)) {
                    return l.libelle();
                }
            }
        }
        return "";
    }
